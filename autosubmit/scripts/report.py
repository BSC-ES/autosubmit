"""report

Generates reports for jobs.

The report is generated by parsing the experiment configuration and can
be used by workflow developers to inspect the parameters available when
writing job templates and shell scripts.

Users can customise the report output by providing report templates.

examples:

    # generate a report for an experiment
    $ autosubmit report a000

    # generate a report using a specific metric template
    $ autosubmit report a000 --template my_template

    # generate a file containing all available parameters
    $ autosubmit report a000 --show_all_parameters

    # generate the report in a specific folder
    $ autosubmit report a000 --folder_path /path/to/reports

    # keep placeholders instead of substituting them
    $ autosubmit report a000 --placeholders
"""

from argparse import ArgumentParser

from autosubmit.scripts._args import (
    CommandGroup,
    ExpidOptions,
    create_argparse_parser,
)
from autosubmit.scripts._cli_function import cli_function
from autosubmit.scripts._validation import validate_expid


class ReportOptions(ExpidOptions):
    """Options for the report command."""

    template: str
    show_all_parameters: bool
    folder_path: str
    placeholders: bool


def args_parser() -> ArgumentParser:
    parser = create_argparse_parser(__doc__)

    parser.add_argument(
        "-t", "--template", type=str, help="Supply the metric template."
    )
    parser.add_argument(
        "-all",
        "--show_all_parameters",
        action="store_true",
        default=False,
        help="Write a file containing all parameters.",
    )
    parser.add_argument(
        "-fp", "--folder_path", type=str, help="Allow to select a non-default folder."
    )
    parser.add_argument(
        "-p",
        "--placeholders",
        default=False,
        action="store_true",
        help="Disable the substitution of placeholders by '-'.",
    )

    return parser


@cli_function(
    args_parser=args_parser,
    group=CommandGroup.WORKFLOW,
    options_type=ReportOptions,
    validators=validate_expid,
)
def main(opts: ReportOptions) -> int | bool | None:
    from autosubmit.experiment.manage import report

    return report(
        opts.expid,
        opts.template,
        opts.show_all_parameters,
        opts.folder_path,
        opts.placeholders,
    )
